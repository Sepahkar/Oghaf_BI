def fix_database_logic():
    if not os.path.exists('oqaf.db'):
        print("Database not found!")
        return

    conn = sqlite3.connect('oqaf.db')
    cursor = conn.cursor()

    print("1. Fixing county names with real data...")
    # اصلاح نام شهرستان‌ها
    cursor.execute("SELECT id, name FROM provinces")
    provinces = cursor.fetchall()
    
    for p_id, p_name in provinces:
        # استان‌های فارس و مازندران چون دیتای واقعی فایل اکسل را دارند اسکیپ می‌شوند
        if p_name in REAL_COUNTIES:
            real_cities = REAL_COUNTIES[p_name]
            cursor.execute("SELECT id FROM counties WHERE province_id = ?", (p_id,))
            counties = cursor.fetchall()
            
            for i, (c_id,) in enumerate(counties):
                # تخصیص نام واقعی به شهرستان‌های رندوم قبلی
                city_name = real_cities[i % len(real_cities)]
                cursor.execute("UPDATE counties SET name = ? WHERE id = ?", (f"شهرستان {city_name}", c_id))

    print("2. Fixing property areas based on logical constraints...")
    # اصلاح مساحت‌ها بر اساس نوع کاربری ملک
    cursor.execute("SELECT id, title FROM properties")
    properties = cursor.fetchall()
    
    for p_id, title in properties:
        area = 100
        if any(keyword in title for keyword in ["تجاری", "غرفه", "دکان", "مغازه"]):
            area = random.randint(12, 150) # 12 تا 150 متر مربع
        elif any(keyword in title for keyword in ["مسکونی", "خانه", "آپارتمان"]):
            area = random.randint(50, 400) # 50 تا 400 متر مربع
        elif any(keyword in title for keyword in ["زراعی", "کشاورزی", "باغ", "بایر"]):
            area = random.randint(2000, 100000) # 2 هزار تا 100 هزار متر (0.2 تا 10 هکتار)
        elif any(keyword in title for keyword in ["دامداری", "کارگاه"]):
            area = random.randint(500, 5000) # 500 تا 5000 متر
        elif "حمام" in title:
            area = random.randint(150, 600) # 150 تا 600 متر
        else:
            area = random.randint(50, 500)
            
        cursor.execute("UPDATE properties SET area = ? WHERE id = ?", (area, p_id))

    conn.commit()
    conn.close()
    print("Database successfully fixed! Real county names and logical areas applied.")

